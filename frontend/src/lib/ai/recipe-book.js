export function getRecipesByPhase(phase) {
  if (!phase || phase === 'TODOS') return RECIPE_BOOK;
  const target = phase.toUpperCase();
  return RECIPE_BOOK.filter(r => r.phase.toUpperCase() === target);
}

export function getRecipesForMeal(mealCategory, phase = 'TODOS') {
  const pool = getRecipesByPhase(phase);
  if (!mealCategory) return pool;

  const cat = mealCategory.toLowerCase();
  if (cat.includes('breakfast') || cat.includes('café')) {
    const res = pool.filter(r => r.mealType === 'breakfast' || r.category.includes('CAFÉ'));
    return res.length > 0 ? res : pool;
  }
  if (cat.includes('main') || cat.includes('almoço') || cat.includes('jantar')) {
    const res = pool.filter(r => r.mealType === 'main_meal' || r.category.includes('ALMOÇO') || r.category.includes('JANTAR'));
    return res.length > 0 ? res : pool;
  }
  if (cat.includes('snack') || cat.includes('lanche') || cat.includes('ceia')) {
    const res = pool.filter(r => r.mealType === 'snack' || r.category.includes('LANCHE') || r.category.includes('SNACK') || r.category.includes('SOBREMESA'));
    return res.length > 0 ? res : pool;
  }
  return pool;
}

export function searchRecipes(query, phase = 'TODOS') {
  const list = getRecipesByPhase(phase);
  if (!query || !query.trim()) return list;
  const q = query.toLowerCase().trim();
  return list.filter(r => 
    r.title.toLowerCase().includes(q) ||
    r.category.toLowerCase().includes(q) ||
    r.ingredients.some(i => i.toLowerCase().includes(q))
  );
}

